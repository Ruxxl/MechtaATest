// Лист 3 "Корзина и оформление" (TC-030..039) из
// Уцененные_товары_тест_кейсы.xlsx — см. TestPlans/Defectives-full-testcases.md.
//
// КРИТИЧНО (см. заголовок defective_unit_page.cy.js и
// BugReport/Товар/defectives_product/README.md): 2026-08-06 выпущена фича —
// уценённые товары теперь можно заказывать с обычной курьерской доставкой,
// старое ограничение "только самовывоз" (на котором построены TC-031..035 в
// исходном плане) снято намеренно. Кейсы ниже адаптированы под РЕАЛЬНОЕ
// поведение, подтверждённое живой разведкой 2026-08-06:
// - Реальный текст предупреждения в корзине: "Обратите внимание. В корзине
//   есть уцененный товар. На него действует скидка в связи с дефектом – это
//   может быть царапина или отсутствие упаковки. Описание дефекта и фото
//   можно посмотреть на странице товара" + кнопка "Понятно" + крестик закрытия.
// - Модалка появляется одинаково и для корзины ТОЛЬКО с уценёнными товарами,
//   и для смешанной корзины (уценённый + обычный) — состав корзины не влияет.
// - Крестик (X) закрывает модалку и оставляет пользователя в корзине БЕЗ
//   перехода на /checkout/ — оформление прерывается, как и ожидал план.
// - После "Понятно" на шаге "2. Способ доставки" доступны оба способа
//   ("Самовывоз" и "Доставка"), без принудительного ограничения.
//
// Настоящее создание заказа (нажатие финальной кнопки оплаты) НЕ
// автоматизируется — в кодовой базе нет ни одного теста, доводящего чек-аут
// до реального заказа (см. поиск по "Оплатить"/"createOrder" — пусто), это
// сознательная граница проекта. TC-036/037/038 (race condition на
// оплате/повторные клики/рассинхрон вкладок) поэтому приближены лёгкими
// UI-проверками, а не реальным оформлением заказа.
const CHECKOUT_WARNING_TEXT = 'В корзине есть уцененный товар';

// testIsolation:false — фикстура defectiveUnit это РЕАЛЬНЫЙ уникальный
// физический экземпляр (serialNumber, сток=1). С testIsolation:true (дефолт)
// каждый it() получает новые cookies -> новую "гостевую" сессию/device-id,
// и backend резервирует единственный сток за ПЕРВЫМ тестом, добавившим товар
// — все последующие it() с их собственным beforeEach-добавлением получают
// пустую корзину ("/empty-basket/"), т.к. физический экземпляр уже занят
// брошенной корзиной предыдущего теста. Добавляем товар ОДИН раз на весь файл
// и сохраняем сессию между it() — это и соответствует реальному сценарию
// пользователя (один раз положил в корзину, потом взаимодействует с чек-аутом).
describe('Уценённые товары: корзина и оформление (TC-030..039)', { testIsolation: false }, () => {

    // Добавление в корзину сделано частью самого первого it() (а не before()),
    // т.к. глобальный вайтлист безобидной ошибки "reading 'add'" регистрируется
    // в support/e2e.js внутри beforeEach — before() выполняется РАНЬШЕ него,
    // и та же безобидная ошибка (не отфильтрованная на этом этапе) валила
    // весь "before all" hook и все тесты в файле сразу.
    // cy.login() — существующая в проекте команда (см. commands.js, уже
    // используется в checkout.cy.js): реальный API-логин тестовым номером
    // 0000000000/0000. БЕЗ авторизации клик "Оформить заказ" показывает
    // модалку входа "Личный кабинет" ВМЕСТО предупреждения об уценённом
    // товаре — разведкой подтверждено, что это два РАЗНЫХ модальных окна,
    // и предупреждение об уценке появляется только ПОСЛЕ авторизации.
    let fixtures;
    before(() => {
        cy.fixture('defectives').then((f) => { fixtures = f; });
        cy.login();
    });

    it('TC-030: уценённый товар добавляется в корзину со стикером "Уценка"', () => {
        // cy.login() — реальный тестовый аккаунт, корзина персистентна МЕЖДУ
        // запусками (не только между it() в одном файле) — очищаем перед
        // стартом, чтобы TC-035 мог надёжно проверить точное число позиций
        cy.visit('/basket/');
        const removeAll = () => {
            cy.get('body').then(($body) => {
                if ($body.find('[class*="i-ph:trash"]').length > 0) {
                    cy.get('[class*="i-ph:trash"]').first().closest('button').click({ force: true });
                    removeAll();
                }
            });
        };
        removeAll();
        cy.visit(fixtures.defectiveUnit.url);
        cy.get('#product-add-to-basket').should('be.visible').click();
        cy.dismissAccessoryUpsell();
        cy.visit('/basket/');
        cy.contains('Смартфон').should('exist');
        cy.contains('Уценка').should('be.visible');
    });

    it('TC-031 (адаптирован): переход к оформлению с уцен. товаром в корзине показывает предупреждающее модальное окно', () => {
        cy.visit('/basket/');
        cy.contains('button', 'Оформить заказ').click();
        cy.contains('Обратите внимание').should('be.visible');
        cy.contains(CHECKOUT_WARNING_TEXT).should('be.visible');
    });

    it('TC-032 (адаптирован под новую фичу доставки): после подтверждения предупреждения доступны ОБА способа доставки, ограничения самовывозом нет', () => {
        cy.visit('/basket/');
        cy.contains('button', 'Оформить заказ').click();
        cy.contains('button', 'Понятно').click();
        cy.url().should('include', '/checkout/');
        cy.contains('button', 'Далее').click();
        // Дублированный mobile/desktop DOM — эти тексты встречаются в скрытых
        // копиях верстки, поэтому только .should('exist'), не 'be.visible'
        cy.contains('Способ доставки').should('exist');
        cy.contains(/Самовывоз/).should('exist');
        cy.contains(/^Доставка$/).should('exist');
    });

    it('TC-033: закрытие предупреждения крестиком прерывает оформление — пользователь остаётся в корзине', () => {
        cy.visit('/basket/');
        cy.contains('button', 'Оформить заказ').click();
        cy.contains(CHECKOUT_WARNING_TEXT).should('be.visible');
        // Крестик — не <button>, а <span class="iconify i-ph:x ...">, тот же
        // паттерн иконочных классов, что и i-ph:trash в других тестах проекта
        cy.get('[class*="i-ph:x"]').first().click({ force: true });
        cy.contains(CHECKOUT_WARNING_TEXT).should('not.exist');
        cy.url().should('include', '/basket/');
        cy.url().should('not.include', '/checkout/');
    });

    it('TC-034 (адаптирован под новую фичу доставки): оформление с курьерской доставкой для уцен. товара не блокируется на фронте', () => {
        cy.visit('/basket/');
        cy.contains('button', 'Оформить заказ').click();
        cy.contains('button', 'Понятно').click();
        cy.contains('button', 'Далее').click();
        cy.contains(/^Доставка$/).click();
        cy.contains(/не можем найти|ошибка|недоступ/i).should('not.exist');
    });

    it('TC-035: смешанная корзина (уцен. + обычный товар) — предупреждение показывается так же, как для корзины только с уцен. товарами', () => {
        cy.visit(fixtures.regularWithDefectiveVariants.url);
        cy.get('#product-add-to-basket').should('be.visible').click();
        cy.dismissAccessoryUpsell();
        cy.visit('/basket/');
        cy.contains(/^[2-9]\d* товар/).should('be.visible');
        cy.contains('button', 'Оформить заказ').click();
        cy.contains(CHECKOUT_WARNING_TEXT).should('be.visible');
    });

    // Реальный race condition (продажа во время оформления) не воспроизвести
    // без создания настоящего заказа и без известного эндпоинта переоценки
    // корзины (в сетевых логах /basket/ отдельного XHR не найдено — состояние,
    // похоже, приходит через SSR) — приближаем тем, что реально можно
    // проверить: перезагрузка страницы чек-аута сразу после подтверждения
    // предупреждения не роняет страницу и не JS-ошибку
    it('TC-036 (приближение race condition): перезагрузка чек-аута сразу после подтверждения предупреждения не роняет страницу', () => {
        const errors = [];
        cy.on('window:before:load', (win) => {
            win.addEventListener('error', (e) => { if (!e.message.includes("reading 'add'")) errors.push(e.message); });
        });
        cy.visit('/basket/');
        cy.contains('button', 'Оформить заказ').click();
        cy.contains('button', 'Понятно').click();
        cy.url().should('include', '/checkout/');
        cy.reload();
        cy.get('body').should('be.visible');
        cy.then(() => {
            expect(errors, 'перезагрузка чек-аута не должна давать JS-ошибок').to.have.length(0);
        });
    });

    // Реальные дубли заказов не проверяем без создания заказа — приближаем:
    // быстрый повторный клик "Понятно" не открывает модалку повторно и не
    // ломает переход на чек-аут (идемпотентность самого UI-подтверждения)
    it('TC-037 (приближение): быстрый повторный клик "Понятно" не создаёт дублирующихся модалок/переходов', () => {
        cy.visit('/basket/');
        cy.contains('button', 'Оформить заказ').click();
        cy.contains('button', 'Понятно').click().click({ force: true });
        cy.url().should('include', '/checkout/');
        cy.contains(CHECKOUT_WARNING_TEXT).should('not.exist');
    });

    // Реальную рассинхронизацию вкладок (удаление в ДРУГОЙ вкладке, пока
    // предупреждение открыто в текущей) не воспроизвести без создания
    // заказа и без второго browser-контекста — приближаем: товар удаляется
    // из корзины (имитация второй вкладки) ПОСЛЕ подтверждения
    // предупреждения, возврат в корзину корректно отражает актуальный состав
    // Упрощено после нескольких нестабильных попыток пересоздавать корзину
    // внутри этого it() (рекурсивная очистка перед добавлением конфликтовала
    // с реальным состоянием аккаунта и иногда подставляла не тот товар) —
    // тест использует товар, УЖЕ лежащий в корзине от предыдущих it() в этом
    // файле (testIsolation:false, см. заголовок describe), без пересоздания
    it('TC-038 (приближение): товар можно удалить из корзины после подтверждения предупреждения об уценке', () => {
        cy.visit('/basket/');
        cy.contains('button', 'Оформить заказ').click();
        cy.contains('button', 'Понятно').click();
        cy.visit('/basket/');
        // cy.contains('Уценка') здесь НЕ годится — на пустой корзине показывается
        // блок рекомендаций, где СВОИ уценённые товары могут попасться случайно;
        // используем заголовок "N товар(а/ов)" самой корзины как однозначный признак.
        // Не проверяем "корзина пуста" — к этому моменту в корзине может быть
        // ещё один товар из TC-035 (testIsolation:false); проверяем именно
        // уменьшение счётчика на 1, а не абсолютную пустоту
        cy.contains(/^(\d+) товар/).then(($el) => {
            const before = parseInt($el.text().match(/\d+/)[0], 10);
            cy.get('[class*="i-ph:trash"]').first().closest('button').click({ force: true });
            cy.reload();
            if (before > 1) {
                cy.contains(new RegExp(`^${before - 1} товар`)).should('be.visible');
            } else {
                cy.contains(/корзина пуста/i).should('be.visible');
            }
        });
    });

    it('TC-039: возврат из чек-аута кнопкой "Назад" и повторный переход в оформление — предупреждение показывается снова корректно', () => {
        // TC-038 перед этим тестом полностью очищает корзину — возвращаем
        // уцен. товар, иначе не будет предупреждения, которое здесь проверяем
        cy.visit(fixtures.defectiveUnit.url);
        cy.get('#product-add-to-basket').should('be.visible').click();
        cy.dismissAccessoryUpsell();
        cy.visit('/basket/');
        cy.contains(/^\d+ товар/).should('be.visible');
        cy.contains('button', 'Оформить заказ').click();
        cy.contains('button', 'Понятно').click();
        cy.url().should('include', '/checkout/');
        cy.go('back');
        cy.url().should('include', '/basket/');
        cy.contains('button', 'Оформить заказ').click();
        cy.contains(CHECKOUT_WARNING_TEXT).should('be.visible');
    });
});
