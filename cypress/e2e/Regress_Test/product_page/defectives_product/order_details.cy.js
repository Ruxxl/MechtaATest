// Лист 4 "Детали заказа" (TC-040..044) из
// Уцененные_товары_тест_кейсы.xlsx — см. TestPlans/Defectives-full-testcases.md.
//
// Вместо создания нового реального заказа (в проекте нет ни одного теста,
// доводящего чек-аут до оплаты — сознательная граница, см. заголовок
// cart_and_checkout.cy.js) используется УЖЕ СУЩЕСТВУЮЩИЙ реальный заказ
// тестового аккаунта (cy.login(), номер 0000000000): заказ № 10394121,
// найден в /cabinet/orders/, содержит 2 уценённые позиции со своими SN —
// готовая фикстура для TC-040/041/044 без побочных эффектов.
//
// НАЙДЕН БАГ (TC-041, см. BUG-002 в BugReport/Товар/defectives_product/):
// название и картинка уценённого товара в деталях заказа НЕ являются
// ссылками — на всей странице всего 4 <a> (логотип/Мои заказы/Главная/
// Избранное), ни одна не ведёт на карточку товара. Проверено обходом DOM.
const KNOWN_DEFECTIVE_ORDER_ID = '10394121';

// testIsolation:false — без него Cypress сбрасывает cookies (в т.ч. сессию
// логина) между it(), а cy.login() в before() выполняется только один раз;
// без этого флага TC-041 и далее теряют авторизацию и не видят заказ вообще
// (тот же паттерн, что и в cart_and_checkout.cy.js)
describe('Уценённые товары: детали заказа (TC-040..044)', { testIsolation: false }, () => {

    before(() => {
        cy.login();
    });

    it('TC-040: к названию уцененного товара в деталях заказа добавлен серийный номер (SN) в скобках', () => {
        cy.visit(`/cabinet/payment/${KNOWN_DEFECTIVE_ORDER_ID}/`);
        cy.contains('Уценка').should('be.visible');
        cy.contains(/\(SN:\s*\w+\)/).should('be.visible');
    });

    // Документирует BUG-002: план ожидает переход на страницу товара по
    // клику на название, по факту элемент не кликабелен вообще (не <a>,
    // без обработчика) — тест намеренно проверяет ОЖИДАЕМОЕ поведение и
    // падает, пока баг не исправлен (тот же паттерн, что TC-011/БАГ в Sheet 1)
    it('TC-041 / БАГ: клик на название уценённого товара должен открывать страницу этого товара', () => {
        cy.visit(`/cabinet/payment/${KNOWN_DEFECTIVE_ORDER_ID}/`);
        // Без тега 'p' — та же дублированная mobile/desktop DOM-разметка,
        // что не раз ловилась в этом проекте; cy.contains(selector, text)
        // берёт первое совпадение по DOM-порядку и может попасть в скрытый
        // дубль. Нескоуп-версия (как в TC-040) находит видимый элемент надёжно
        cy.contains(/\(SN:/).click();
        cy.url().should('include', '/product/');
    });

    // TC-042 адаптирован: раз название товара НЕ кликабельно вообще (BUG-002)
    // ни для одной позиции, негативный сценарий "клик по удалённому товару"
    // неприменим буквально — проверяем позитивную часть требования: SN и
    // состав заказа отображаются стабильно независимо от статуса товара
    // в живом каталоге (сама страница деталей заказа не зависит от каталога)
    it('TC-042 (адаптирован): SN и состав позиций в заказе отображаются корректно вне зависимости от статуса товара в каталоге', () => {
        cy.visit(`/cabinet/payment/${KNOWN_DEFECTIVE_ORDER_ID}/`);
        cy.contains(/\(SN:\s*\w+\)/).should('be.visible');
        // Сторонние SSR-скрипты (TikTok/Facebook, window.__NUXT__) сами
        // содержат литеральную строку "undefined" в своём коде — вырезаем
        // <script> перед проверкой, иначе ложное срабатывание
        cy.get('body').then(($body) => {
            const clone = $body.clone();
            clone.find('script').remove();
            expect(clone.text()).to.not.include('undefined');
        });
    });

    // TC-043 (отмена заказа -> возврат остатка в 1С/MDM) НЕ автоматизирован:
    // заказ №10394121 — единственная найденная живая фикстура с несколькими
    // уценёнными позициями (нужна TC-040/041/044); отмена — вероятно
    // необратимое изменение статуса, которое сломало бы её для дальнейших
    // прогонов и других сессий. Возврат остатка в 1С/MDM в принципе не
    // проверяем через UI/публичный API. Оставлено как ручной/exploratory кейс.

    it('TC-044: несколько уцененных позиций в заказе — у каждой свой SN, номера не перепутаны', () => {
        cy.visit(`/cabinet/payment/${KNOWN_DEFECTIVE_ORDER_ID}/`);
        // Дожидаемся реального рендера (retry-ability), прежде чем читать
        // текст напрямую — без этого $body.text() иногда читается до того,
        // как контент дорисован
        cy.contains(/\(SN:/).should('be.visible');
        cy.get('body').invoke('text').then((text) => {
            const serials = [...text.matchAll(/\(SN:\s*([\w-]+)\)/g)].map((m) => m[1]);
            expect(serials.length, 'в заказе должно быть минимум 2 уценённые позиции с SN').to.be.greaterThan(1);
            const unique = new Set(serials);
            expect(unique.size, 'серийные номера у разных позиций не должны совпадать/дублироваться').to.eq(serials.length);
        });
    });
});
