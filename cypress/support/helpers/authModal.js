// Модалка входа ("Личный кабинет") переиспользуется в нескольких местах сайта —
// кнопка "Оформить заказ" в корзине, "Купить сейчас" на странице товара, "Войти"
// в шапке. Логика проверки этой модалки вынесена сюда, чтобы не дублировать
// одни и те же селекторы/тексты в разных page object'ах.

// Появляется при попытке совершить действие, требующее авторизации, будучи анонимом.
// В отличие от прямого захода на /checkout/ (там сайт делает редирект на главную),
// здесь показывается модалка логина без ухода со страницы.
export function assertLoginModalShown() {
    cy.contains('Вы не авторизованы').should('be.visible');
    cy.contains('h3', 'Личный кабинет').should('be.visible');
}

// Ввод телефона неверного формата должен блокировать переход дальше и показывать
// текст ошибки под полем. Поле называется name="mobile" (не "phone").
export function assertInvalidPhoneShowsValidationError(phone) {
    cy.get('input[name="mobile"]').first().as('phoneInput');
    cy.get('@phoneInput').clear();
    if (phone) {
        cy.get('@phoneInput').type(phone);
    }
    cy.contains('button', 'Выслать код').click();
    cy.contains('Введите номер телефона в формате').should('be.visible');
    // Модалка должна остаться на шаге ввода телефона, а не перейти к вводу кода
    cy.get('@phoneInput').should('be.visible');
}
